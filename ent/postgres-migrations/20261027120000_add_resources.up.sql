-- The resource index: which local filesystem paths and URLs a recorded
-- exchange carried, for the trace detail and the cross-session resources page.
--
-- This is deliberately two tables. `resources` is the global catalogue, one row
-- per distinct (kind, value), so a path an agent reads on every run does not add
-- a row per request; `trace_resources` is the per-trace relation that answers
-- "what did this trace touch" and supplies the trace_count/access_count the
-- catalogue page aggregates. Neither table stores file content.
--
-- The unique key is the SHA-256 of (kind, value) rather than the value itself:
-- a long URL would otherwise approach the btree key size limit, and the full
-- value is still kept for display. Counts are computed from trace_resources on
-- read, so a reparse replaces the trace's rows without delta arithmetic.
CREATE TABLE "resources" (
  "id" bigint GENERATED BY DEFAULT AS IDENTITY,
  "kind" character varying NOT NULL DEFAULT '',
  "value" text NOT NULL DEFAULT '',
  "value_hash" character varying NOT NULL DEFAULT '',
  "last_trace_id" character varying NOT NULL DEFAULT '',
  "first_seen_at" timestamptz NOT NULL,
  "last_seen_at" timestamptz NOT NULL,
  PRIMARY KEY ("id")
);

CREATE UNIQUE INDEX "resource_kind_value_hash" ON "resources" ("kind", "value_hash");
CREATE INDEX "resource_last_seen_at_id" ON "resources" ("last_seen_at" DESC, "id" DESC);

CREATE TABLE "trace_resources" (
  "trace_id" character varying NOT NULL,
  "resource_id" bigint NOT NULL,
  "access_count" bigint NOT NULL DEFAULT 0,
  "first_position" bigint NOT NULL DEFAULT 0,
  "created_at" timestamptz NOT NULL,
  PRIMARY KEY ("trace_id", "resource_id")
);

-- The primary key serves the per-trace list; this one serves the catalogue's
-- "how many traces used this value" and "which traces" queries.
CREATE INDEX "traceresource_resource_id_trace_id" ON "trace_resources" ("resource_id", "trace_id");
